var MediaTemplatesPlugin = class extends import_obsidian4.Plugin {
  async onload() {
    await this.loadSettings();
    this.api = {
      getMediaList: () => this.settings.mediaLibrary,
      getMedia: (id) => this.settings.mediaLibrary.find((m) => m.id === id),
      getMediaByTitle: (title) => this.settings.mediaLibrary.find(
        (m) => m.title.toLowerCase() === title.toLowerCase()
      ),
      getNoteTypes: () => NOTE_TYPES,
      createNote: (ctx) => this.createNote(ctx)
    };
    window["MediaTemplates"] = {
      plugin: this,
      api: this.api
    };
    this.addCommand({
      id: "create-media-note",
      name: "Create media note",
      callback: () => openCreateNoteFlow(this.app, this)
    });
    this.addCommand({
      id: "add-media-to-library",
      name: "Add media to library",
      callback: () => {
        new AddMediaModal(this.app, async (media) => {
          this.settings.mediaLibrary.push(media);
          await this.saveSettings();
          new import_obsidian4.Notice(`Added "${media.title}" to your library.`);
        }).open();
      }
    });
    this.addCommand({
      id: "create-series-index",
      name: "Create series index for media",
      callback: () => {
        const list = this.settings.mediaLibrary;
        if (!list.length) {
          new import_obsidian4.Notice("No media in library. Add some first.", 3e3);
          return;
        }
        openCreateNoteFlow(this.app, this);
      }
    });
    this.addSettingTab(new SettingsTab(this.app, this));
    console.log("[Media Templates] Plugin loaded.");
  }
  onunload() {
    delete window["MediaTemplates"];
    console.log("[Media Templates] Plugin unloaded.");
  }
  // ── Settings persistence ──────────────────────────────────────────────────
  async loadSettings() {
    this.settings = Object.assign({}, DEFAULT_SETTINGS, await this.loadData());
  }
  async saveSettings() {
    await this.saveData(this.settings);
  }
  // ── Core note creation ────────────────────────────────────────────────────
  async createNote(ctx) {
    const noteTypeInfo = getNoteTypeInfo(ctx.noteType);
    const media = ctx.media;
    const mediaFolder = (media.noteFolder || `${this.settings.defaultMediaFolder}/${media.title}`).replace(/\/$/, "");
    const subFolder = noteTypeInfo.subFolder;
    const folderPath = (0, import_obsidian4.normalizePath)(
      subFolder ? `${mediaFolder}/${subFolder}` : mediaFolder
    );
    if (this.settings.autoCreateFolders) {
      await this.ensureFolder(folderPath);
    }
    const safeTitle = ctx.title.replace(/[\\/:*?"<>|]/g, "-");
    const filePath = (0, import_obsidian4.normalizePath)(`${folderPath}/${safeTitle}.md`);
    const existing = this.app.vault.getAbstractFileByPath(filePath);
    if (existing instanceof import_obsidian4.TFile) {
      new import_obsidian4.Notice(`Note "${safeTitle}" already exists \u2014 opening it.`, 3e3);
      return existing;
    }
    const content = buildNoteContent(ctx);
    return await this.app.vault.create(filePath, content);
  }
  async ensureFolder(path) {
    const parts = path.split("/").filter(Boolean);
    let current = "";
    for (const part of parts) {
      current = current ? `${current}/${part}` : part;
      const exists = this.app.vault.getAbstractFileByPath(current);
      if (!exists) {
        await this.app.vault.createFolder(current);
      } else if (!(exists instanceof import_obsidian4.TFolder)) {
        throw new Error(
          `Path "${current}" exists but is a file, not a folder.`
        );
      }
    }
  }
  // ── Convenience helper for QuickAdd / Templater scripts ──────────────────
  /** Returns a slug-safe version of the media title */
  static toSlug(title) {
    return toSlug(title);
  }
};
