var NoteTitleModal = class extends import_obsidian3.Modal {
  constructor(app, noteType, media, defaultTitle, callback) {
    super(app);
    this.noteType = noteType;
    this.media = media;
    this.defaultTitle = defaultTitle;
    this.callback = callback;
    this.title = "";
    this.season = "";
    this.episode = "";
    this.title = defaultTitle;
  }
  onOpen() {
    const { contentEl } = this;
    contentEl.empty();
    contentEl.addClass("media-templates-modal");
    contentEl.createEl("h2", { text: `New ${this.noteType.label}` });
    contentEl.createEl("p", {
      text: `For: ${this.media.title}`,
      cls: "setting-item-description"
    });
    if (this.noteType.asksForSeason) {
      new import_obsidian3.Setting(contentEl).setName("Season").setDesc("Season number (leave blank for season 1)").addText((text) => {
        text.setPlaceholder("1").setValue(this.season).onChange((v) => this.season = v);
      });
    }
    if (this.noteType.asksForEpisode) {
      new import_obsidian3.Setting(contentEl).setName("Episode").setDesc("Episode number within the season").addText((text) => {
        text.setPlaceholder("1").setValue(this.episode).onChange((v) => this.episode = v);
      });
    }
    new import_obsidian3.Setting(contentEl).setName("Title").setDesc(`Name for this ${this.noteType.label.toLowerCase()} note`).addText((text) => {
      text.setPlaceholder(`${this.noteType.label} title\u2026`).setValue(this.title).onChange((v) => this.title = v);
      setTimeout(() => {
        text.inputEl.focus();
        text.inputEl.select();
      }, 50);
      text.inputEl.addEventListener("keydown", (e) => {
        if (e.key === "Enter") this.submit();
      });
    });
    new import_obsidian3.Setting(contentEl).addButton(
      (btn) => btn.setButtonText("Create Note").setCta().onClick(() => this.submit())
    ).addButton(
      (btn) => btn.setButtonText("Cancel").onClick(() => this.close())
    );
  }
  submit() {
    const finalTitle = this.title.trim();
    if (!finalTitle) {
      new import_obsidian3.Notice("Please enter a title.");
      return;
    }
    this.close();
    this.callback(finalTitle, this.season || "1", this.episode || "1");
  }
  onClose() {
    this.contentEl.empty();
  }
};
function openCreateNoteFlow(app, plugin) {
  const mediaList = plugin.settings.mediaLibrary;
  if (mediaList.length === 0) {
    new import_obsidian3.Notice(
      "No media in your library yet. Add some in Media Templates settings.",
      4e3
    );
    return;
  }
  new MediaSuggestModal(app, mediaList, (media) => {
    const relevantTypes = NOTE_TYPES.filter(
      (t) => !t.showOnlyFor || t.showOnlyFor.includes(media.type)
    );
    new NoteTypeSuggestModal(app, relevantTypes, (noteType) => {
      const defaultTitle = buildDefaultTitle(media, noteType);
      new NoteTitleModal(app, noteType, media, defaultTitle, (title, season, episode) => {
        plugin.createNote({ media, noteType: noteType.id, title, season, episode }).then((file) => {
          if (plugin.settings.openAfterCreate) {
            const leaf = app.workspace.getLeaf(false);
            leaf.openFile(file);
          }
          new import_obsidian3.Notice(`Created: ${title}`);
        }).catch((err) => {
          new import_obsidian3.Notice(`Error creating note: ${err.message}`);
          console.error("[Media Templates]", err);
        });
      }).open();
    }).open();
  }).open();
}
function buildDefaultTitle(media, noteType) {
  switch (noteType.id) {
    case "series-index":
      return media.title;
    case "season-overview":
      return `${media.title} \u2014 Season `;
    case "episode":
      return `${media.title} S01E01 \u2014 `;
    default:
      return "";
  }
}

